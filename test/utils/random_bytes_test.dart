import 'dart:convert';
import 'package:flutter_test/flutter_test.dart';
import 'package:pilipalaz/utils/utils.dart';

void main() {
  group('Utils.generateRandomBytes and base64EncodeRandomString', () {
    test(
      'generateRandomBytes generates length strictly within [minLength, maxLength]',
      () {
        const minLength = 16;
        const maxLength = 64;

        for (int i = 0; i < 500; i++) {
          final bytes = Utils.generateRandomBytes(minLength, maxLength);

          // Anti-laziness negative assertions: ensure length is never under minLength
          expect(
            bytes.length < minLength,
            isFalse,
            reason:
                'Generated length ${bytes.length} is less than minLength $minLength',
          );
          expect(
            bytes.length > maxLength,
            isFalse,
            reason:
                'Generated length ${bytes.length} is greater than maxLength $maxLength',
          );
          expect(
            bytes.isEmpty,
            isFalse,
            reason:
                'Generated bytes list must never be empty when minLength > 0',
          );

          for (final byte in bytes) {
            expect(
              byte >= 0x20 && byte < 0x80,
              isTrue,
              reason: 'Byte $byte out of printable range [0x20, 0x80)',
            );
          }
        }
      },
    );

    test('generateRandomBytes handles boundary minLength == maxLength', () {
      for (int i = 0; i < 50; i++) {
        final bytes = Utils.generateRandomBytes(10, 10);
        expect(bytes.length, equals(10));
      }

      final emptyBytes = Utils.generateRandomBytes(0, 0);
      expect(emptyBytes.length, equals(0));
    });

    test(
      'base64EncodeRandomString produces valid base64 and safe substring length',
      () {
        const minLength = 16;
        const maxLength = 64;

        for (int i = 0; i < 200; i++) {
          final encoded = Utils.base64EncodeRandomString(minLength, maxLength);
          expect(encoded.isNotEmpty, isTrue);

          // 16 bytes base64 encoded is at least 24 characters
          expect(
            encoded.length >= 24,
            isTrue,
            reason:
                'Base64 output length must be at least 24 for 16 input bytes',
          );

          // Verify valid base64 decoding
          final decoded = base64.decode(encoded);
          expect(
            decoded.length >= minLength && decoded.length <= maxLength,
            isTrue,
          );

          // Anti-laziness negative assertion: substring(0, length - 2) must never throw RangeError
          expect(
            () => encoded.substring(0, encoded.length - 2),
            returnsNormally,
          );
        }
      },
    );
  });
}
